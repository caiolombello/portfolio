/**
 * Blog figures with theme and screen-size variants.
 *
 * Markdown references only the wide light file (for example
 * `![alt](/images/posts/hub-and-spoke-aws/fluxo-rede.svg)`). When that path is
 * registered here, the renderer adds the dark and narrow variants. Sizes must
 * match each SVG's width/height attributes (checked in blog-figures.test.ts).
 * Registered figures ignore the Markdown title; put captions in the paragraph
 * after the image.
 */

export interface FigureAsset {
  src: string;
  width: number;
  height: number;
}

export interface FigureVariantSet {
  light: FigureAsset;
  dark?: FigureAsset;
}

export interface BlogFigure {
  /** Layout used from the `sm` breakpoint up. */
  wide: FigureVariantSet;
  /** Layout for phones, selected with NARROW_FIGURE_MEDIA. */
  narrow?: FigureVariantSet;
}

export const NARROW_FIGURE_MEDIA = "(max-width: 639px)";

interface Size {
  width: number;
  height: number;
}

/**
 * Builds a figure whose files follow `<base>[.mobile][.dark].svg`. Dark
 * variants share the geometry of their light counterpart.
 */
function svgFigure(base: string, wide: Size, narrow: Size): BlogFigure {
  return {
    wide: {
      light: { src: `${base}.svg`, ...wide },
      dark: { src: `${base}.dark.svg`, ...wide },
    },
    narrow: {
      light: { src: `${base}.mobile.svg`, ...narrow },
      dark: { src: `${base}.mobile.dark.svg`, ...narrow },
    },
  };
}

const HUB_AND_SPOKE = "/images/posts/hub-and-spoke-aws";

// Generated by scripts/diagrams/hub-and-spoke-aws.mjs, which prints the sizes.
const figures: BlogFigure[] = [
  svgFigure(
    `${HUB_AND_SPOKE}/fluxo-rede`,
    { width: 1000, height: 1255 },
    { width: 600, height: 2017 },
  ),
  svgFigure(
    `${HUB_AND_SPOKE}/fluxo-rede.en`,
    { width: 1000, height: 1255 },
    { width: 600, height: 1991 },
  ),
];

export const BLOG_FIGURES: ReadonlyMap<string, BlogFigure> = new Map(
  figures.map((figure) => [figure.wide.light.src, figure]),
);

export function getBlogFigure(src: unknown): BlogFigure | undefined {
  return typeof src === "string" ? BLOG_FIGURES.get(src) : undefined;
}
